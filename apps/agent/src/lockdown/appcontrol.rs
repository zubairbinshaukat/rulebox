/// The fixed id of the recommended block rules policy (`RB-BLOCKS`, plan 4.9): the
/// `PolicyID` of `recommended-blocks.xml`, lowercase, no braces.
pub const BLOCKS_ID: &str = "427ecba1-e86b-448b-8dd8-04977e362e28";
/// The fixed id of the allow-list policy (`RB-ALLOW`): `allowlist.xml`.
pub const ALLOW_ID: &str = "b0cfa9cb-9fa5-40f0-ad43-889657fdbb06";
/// The only policy ids the agent ever deploys, restores or reports as its own.
pub const RULEBOX_POLICY_IDS: [&str; 2] = [BLOCKS_ID, ALLOW_ID];

/// The `VersionEx` of each XML source, by source name. It must increase with every content
/// change of that XML; a test compares it with the file.
pub const POLICY_VERSIONS: [(&str, &str); 2] = [("recommended-blocks", "1.0.0.0"), ("allowlist", "1.0.0.0")];

/// First build with the multiple-policy format (Windows 10 1903).
pub const MIN_BUILD_MULTIPLE_POLICY: u32 = 18362;
/// First build with `CiTool.exe` (Windows 11 22H2); also Windows Server 2025.
pub const MIN_BUILD_CITOOL: u32 = 22621;

/// Which binary of a policy: the one with `Enabled:Audit Mode`, or the enforcing one.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Variant {
    Audit,
    Enforce,
}

impl Variant {
    pub fn word(self) -> &'static str {
        match self {
            Variant::Audit => "audit",
            Variant::Enforce => "enforce",
        }
    }
}

/// One embedded policy binary (generated by `build.rs`, see [`EMBEDDED`]).
#[derive(Debug, Clone, Copy)]
pub struct EmbeddedPolicy {
    /// The XML source name (`recommended-blocks`, `allowlist`).
    pub name: &'static str,
    /// The policy id (lowercase GUID, no braces).
    pub id: &'static str,
    /// `VersionEx` of the XML it was built from.
    pub version: &'static str,
    pub variant: Variant,
    /// SHA-256 of `bytes` (lowercase hex).
    pub sha256: &'static str,
    pub bytes: &'static [u8],
}

include!(concat!(env!("OUT_DIR"), "/appcontrol_embedded.rs"));

/// The embedded binary of `id` in `variant`.
pub fn embedded(id: &str, variant: Variant) -> Option<&'static EmbeddedPolicy> {
    EMBEDDED.iter().find(|policy| policy.id == id && policy.variant == variant)
}

/// The agent-state mark of a change that waits for a restart.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct CiRestartMark {
    /// Unix ms when the change was made (the wall-clock fallback of `rebooted_since`).
    pub since_ms: u64,
    /// The boot it was made in, when the boot counters could be read.
    pub boot: Option<BootMark>,
}

// ---------------------------------------------------------------- the decision

/// How a change becomes active.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Activation {
    /// `CiTool --refresh` (Windows 11 22H2 and later).
    Refresh,
    /// Only a restart loads it.
    Restart,
}

/// What the layer does for one mode, level and Windows build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Plan {
    /// `off`: remove the policies the agent deployed.
    Remove,
    /// Deploy these policies (id and variant); remove the other Rulebox one if it is ours.
    Deploy(Vec<(&'static str, Variant)>),
    /// A value this build does not know: change nothing. The code is the layer detail.
    LeaveAlone(&'static str),
    /// This Windows cannot run the layer: deploy nothing. The code is the layer detail.
    Unsupported(&'static str),
}

impl Plan {
    /// The ids that should be on the PC (empty for everything but `Deploy`).
    pub fn wanted(&self) -> Vec<&'static str> {
        match self {
            Plan::Deploy(policies) => policies.iter().map(|(id, _)| *id).collect(),
            _ => Vec::new(),
        }
    }
}

/// The decision table (plan 4.9 and Q1).
pub fn decide(mode: LayerMode, level: AppControlLevel, build: u32) -> Plan {
    let variant = match mode {
        LayerMode::Off => return Plan::Remove,
        LayerMode::Unknown => return Plan::LeaveAlone("section_unknown_value"),
        LayerMode::Audit => Variant::Audit,
        LayerMode::Enforce => Variant::Enforce,
    };
    let policies = match level {
        AppControlLevel::RecommendedBlocks => vec![(BLOCKS_ID, variant)],
        AppControlLevel::Allowlist => vec![(BLOCKS_ID, variant), (ALLOW_ID, variant)],
        AppControlLevel::Unknown => return Plan::LeaveAlone("section_unknown_value"),
    };
    if build < MIN_BUILD_MULTIPLE_POLICY {
        return Plan::Unsupported("os_too_old_for_app_control");
    }
    Plan::Deploy(policies)
}

/// How a change on this build becomes active.
pub fn activation_for(build: u32) -> Activation {
    if build >= MIN_BUILD_CITOOL {
        Activation::Refresh
    } else {
        Activation::Restart
    }
}

/// The code of the refusal of level `allowlist` while an app sits outside the allowed folders.
pub const ALLOWLIST_USER_INSTALL: &str = "allowlist_level_with_user_install";

fn path_key(path: &str) -> String {
    path.replace('/', "\\").trim_end_matches('\\').to_ascii_lowercase()
}

fn inside(path: &str, root: &str) -> bool {
    let (path, root) = (path_key(path), path_key(root));
    !root.is_empty() && (path == root || (path.starts_with(&root) && path.as_bytes().get(root.len()) == Some(&b'\\')))
}

/// The folders the allow-list policy lets programs start from: Program Files (and its x86 and
/// Arm folders) and the Windows folder (the Rulebox folder is inside Program Files).
pub fn allowed_roots(roots: &PathRoots) -> Vec<String> {
    let mut out = vec![roots.program_files.clone(), format!("{} (Arm)", roots.program_files)];
    out.extend(roots.program_files_x86.clone());
    out.extend(roots.system_root.clone());
    out
}

/// Level `allowlist` is refused while a catalogue app starts from outside [`allowed_roots`]
/// (edge case 48). Pure: nothing is written either way.
pub fn check_allowlist_level(facts: &Facts, roots: &PathRoots) -> Result<(), &'static str> {
    let allowed = allowed_roots(roots);
    if facts.catalogue_exe_folders.iter().all(|folder| allowed.iter().any(|root| inside(folder, root))) {
        Ok(())
    } else {
        Err(ALLOWLIST_USER_INSTALL)
    }
}

// ---------------------------------------------------------------- the layer

fn reported_mode(mode: LayerMode) -> ReportedMode {
    match mode {
        LayerMode::Audit => ReportedMode::Audit,
        LayerMode::Enforce => ReportedMode::Enforce,
        LayerMode::Off | LayerMode::Unknown => ReportedMode::Off,
    }
}

fn state(mode: ReportedMode, state: LayerStatus, detail: Option<&str>) -> LayerState {
    LayerState { mode, state, detail: detail.map(str::to_string) }
}

fn boot_mark(platform: &dyn Platform) -> Option<BootMark> {
    platform.boot_identity().ok().map(|boot| BootMark { boot_id: boot.boot_id, uptime_ms: boot.uptime_ms })
}

/// True while an earlier change still waits for a restart; clears the mark once the PC booted.
fn restart_still_pending(ctx: &ApplyCtx<'_>) -> bool {
    let Some(mark) = ctx.journal.shared.read(|state| state.ci_restart) else {
        return false;
    };
    match ctx.journal.platform.boot_identity() {
        Ok(now) if rebooted_since(mark.boot.as_ref(), mark.since_ms, &now) => {
            let _ = ctx.journal.shared.update(|state| state.ci_restart = None);
            false
        }
        // Not booted since, or the boot cannot be read: keep waiting (the safe side).
        _ => true,
    }
}

/// Applies or removes the layer. Idempotent: a second run with the same document writes and
/// refreshes nothing.
pub fn apply(ctx: &ApplyCtx<'_>, doc: &AgentDoc) -> LayerState {
    apply_with(ctx, doc, APPCONTROL_BUILT)
}

/// The code of the refusal to deploy when this agent was built without the policy binaries
/// (`build.rs`, no `target\appcontrol\`); removal still works.
pub const NOT_BUILT: &str = "appcontrol_not_built";

/// [`apply`] with the "binaries were embedded" flag explicit, so a test can drive both builds.
fn apply_with(ctx: &ApplyCtx<'_>, doc: &AgentDoc, built: bool) -> LayerState {
    let platform = ctx.journal.platform;
    let (mode, level) =
        doc.lockdown.as_ref().map_or((LayerMode::Off, AppControlLevel::RecommendedBlocks), |p| (p.app_control.mode, p.app_control.level));
    let shown = reported_mode(mode);

    // The Windows build is only needed to deploy; `off` works on any build.
    let build = if mode == LayerMode::Off {
        0
    } else {
        match platform.os_info() {
            Ok(os) => os.build,
            Err(_) => return state(shown, LayerStatus::Failed, Some("os_info_unreadable")),
        }
    };
    let plan = decide(mode, level, build);
    match &plan {
        Plan::LeaveAlone(code) => return state(ReportedMode::Off, LayerStatus::Ok, Some(code)),
        Plan::Unsupported(code) => return state(shown, LayerStatus::Unsupported, Some(code)),
        Plan::Remove | Plan::Deploy(_) => {}
    }
    // An agent built without the policy binaries deploys nothing and says why. Nothing is
    // written, nothing removed: an earlier deployment stays until `off` or Disable restores it.
    if matches!(plan, Plan::Deploy(_)) && !built {
        return state(shown, LayerStatus::Failed, Some(NOT_BUILT));
    }
    if plan.wanted().contains(&ALLOW_ID) {
        match platform.path_roots() {
            Ok(roots) => {
                if let Err(code) = check_allowlist_level(&ctx.facts, &roots) {
                    return state(shown, LayerStatus::Failed, Some(code));
                }
            }
            Err(_) => return state(shown, LayerStatus::Failed, Some("path_roots_unreadable")),
        }
    }

    let mut tally = Tally::default();
    let mut changed = false;

    // Deploy what is wanted, in the variant of the mode.
    if let Plan::Deploy(policies) = &plan {
        for (id, variant) in policies {
            let Some(policy) = embedded(id, *variant) else {
                tally.record(Err("policy_not_embedded"));
                continue;
            };
            let change = Change::ci_policy(JournalOwner::L4, id, policy.bytes).since(ctx.version);
            match journal::change(&ctx.journal, &change) {
                Ok(outcome) => {
                    changed |= outcome == ChangeOutcome::Written;
                    tally.record(Ok(()));
                }
                Err(error) => tally.record(Err(journal::error_code(&error))),
            }
        }
    }

    // Remove the Rulebox policies that are not wanted and that the journal says we deployed.
    let wanted = plan.wanted();
    let stale: Vec<String> = ctx.journal.shared.read(|state| {
        RULEBOX_POLICY_IDS
            .iter()
            .filter(|id| !wanted.contains(id))
            .map(|id| journal::ci_id(id))
            .filter(|entry_id| state.journal.iter().any(|entry| &entry.id == entry_id))
            .collect()
    });
    if !stale.is_empty() {
        let report = journal::restore_ids(&ctx.journal, &stale);
        changed |= !report.restored.is_empty();
        for _ in &report.restored {
            tally.record(Ok(()));
        }
        for (_, error) in &report.failed {
            tally.record(Err(journal::error_code(error)));
        }
    }

    // Activation.
    let mut needs_restart = false;
    if changed {
        needs_restart = match activation_for(build_for_activation(platform, build)) {
            Activation::Refresh => platform.refresh_ci_policies().is_err(),
            Activation::Restart => true,
        };
        if needs_restart {
            let mark = CiRestartMark { since_ms: ctx.now_ms, boot: boot_mark(platform) };
            if ctx.journal.shared.update(|state| state.ci_restart = Some(mark)).is_err() {
                tally.record(Err("state_not_saved"));
            }
        }
    }
    let waiting = needs_restart || restart_still_pending(ctx);

    let status = match tally.status() {
        LayerStatus::Ok if waiting => LayerStatus::RestartPending,
        other => other,
    };
    let detail = tally.detail().or_else(|| waiting.then(|| "restart_needed".to_string()));
    LayerState { mode: shown, state: status, detail }
}

/// The build that decides the activation. `off` does not read the build (it works on every
/// Windows), but a removal still needs it to pick refresh or restart.
fn build_for_activation(platform: &dyn Platform, known: u32) -> u32 {
    if known != 0 {
        return known;
    }
    platform.os_info().map_or(0, |os| os.build)
}

// ---------------------------------------------------------------- the report

/// One Rulebox policy file on the PC.
#[derive(Serialize, Debug, Clone, PartialEq, Eq)]
#[serde(rename_all = "camelCase")]
pub struct DeployedPolicy {
    pub id: &'static str,
    /// `audit` / `enforce` when the file is exactly the embedded binary of that variant;
    /// `None` for any other content under the id (an older Rulebox build).
    pub variant: Option<&'static str>,
}

/// What the agent reports about this layer (`ciPolicies`, plan 4.19): Rulebox ids only, other
/// products' policies are never listed.
#[derive(Serialize, Debug, Clone, PartialEq, Eq, Default)]
#[serde(rename_all = "camelCase")]
pub struct AppControlReport {
    pub ci_policies: Vec<String>,
    pub deployed: Vec<DeployedPolicy>,
}

/// Reads the active folder (read-only) and describes the Rulebox policies in it.
pub fn report(platform: &dyn Platform) -> Result<AppControlReport, PlatformError> {
    let mut report = AppControlReport::default();
    for id in RULEBOX_POLICY_IDS {
        let Some(bytes) = platform.read_ci_policy(id)? else {
            continue;
        };
        let hash = journal::policy_hash(&bytes);
        let variant = [Variant::Audit, Variant::Enforce]
            .into_iter()
            .find(|variant| embedded(id, *variant).is_some_and(|policy| policy.sha256 == hash))
            .map(Variant::word);
        report.ci_policies.push(id.to_string());
        report.deployed.push(DeployedPolicy { id, variant });
    }
    Ok(report)
}

