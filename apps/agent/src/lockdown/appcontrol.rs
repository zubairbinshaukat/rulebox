//! L4, App Control for Business (plan 4.9, Phase 5 Step 6).
//!
//! Two static, unsigned, multiple-policy-format base policies are embedded in the agent
//! (`build.rs`, from `target\appcontrol\*.cip`, built by `scripts/appcontrol-build.ps1` out of
//! `apps/agent/policies/appcontrol/*.xml`), each as an audit and an enforce binary. A build
//! without them (fresh clone, CI, Windows Home) still compiles with [`APPCONTROL_BUILT`]
//! `false`: the layer then reports `appcontrol_not_built` for any deploy and writes nothing:
//!
//! | Policy | Id | Content | Deployed |
//! |---|---|---|---|
//! | `recommended-blocks` | [`BLOCKS_ID`] | Microsoft's recommended block rules, allow-all otherwise | whenever the layer is on |
//! | `allowlist` | [`ALLOW_ID`] | Windows-signed code and the Windows, Program Files and Rulebox folders | only with level `allowlist` |
//!
//! * **Decision** ([`decide`]): `appControl.mode` x `appControl.level` x the Windows build.
//!   `off` removes both. `audit` / `enforce` deploy the policy (or, with `allowlist`, both
//!   policies: a file must pass every base policy, so the allow list never lifts a Microsoft
//!   block rule) in the matching variant. A mode or level this build does not know changes
//!   nothing. Below Windows 10 1903 (build 18362) the multiple-policy format does not exist:
//!   the layer reports `unsupported`.
//! * **Journal**: every policy file goes through `journal::change` (owner `L4`, target
//!   `CiPolicy`, id `ci:<policy id>`, original "not there"), so Disable, `unenroll` and
//!   `recover` remove it again through the same restore as everything else.
//! * **Only our two ids.** Nothing but [`RULEBOX_POLICY_IDS`] is ever passed to the seam. A
//!   policy file the agent did not deploy (another product's policy, or a Rulebox id with no
//!   journal entry) is never edited, merged or removed; [`report`] only lists it. A Rulebox
//!   id that is *wanted* and already on disk without an entry is taken over (the id is fixed,
//!   so the file can only be an older Rulebox deployment whose journal was lost).
//! * **Activation.** After a change the agent asks Windows to load it with `CiTool --refresh`
//!   (Windows 11 22H2, build 22621, and later). On older builds, or when the refresh fails, the
//!   layer reports `restartPending` until the PC has booted (the mark lives in the agent state;
//!   the agent never restarts the PC, edge case 43). Whether `--refresh` also drops a policy
//!   whose file was removed, and whether Home accepts unsigned base policies, are
//!   **unverified** until the VM run (Step 21).
//! * `allowlist` is refused while the catalogue has an app outside the allowed folders
//!   ([`check_allowlist_level`], `allowlist_level_with_user_install`); nothing is written.
//!
//! Audit before enforce (invariant I9, a 24 h audit period first) is a shared mechanism of the
//! layers that have an `enforce` mode and is not part of this step.

