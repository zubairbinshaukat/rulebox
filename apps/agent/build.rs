//! Links the Visual C++ runtime (`vcruntime140.dll`) into `rulebox-agent.exe`
//! statically, so the service starts on a clean Windows that has no Visual C++
//! Redistributable. Found on the VM: without this the agent exits with
//! `0xC0000135` (a DLL was not found) before it can log anything.
//!
//! Only the vcruntime part goes static; the Universal C Runtime is part of Windows
//! 10 and later. This is what the `static_vcruntime` crate does, without a
//! dependency. It applies to this package's binary only, so Tauri and the test
//! harnesses are untouched.

//! (Phase 5 Step 6) It also embeds the App Control policy binaries that
//! `scripts/appcontrol-build.ps1` writes to `<workspace>/target/appcontrol/`: four `.cip`
//! files (two policies, audit and enforce) with their SHA-256. Binaries older than their XML
//! source fail the build with a message naming the script.
//!
//! Missing binaries (a fresh clone, CI, Windows Home where ConfigCI does not exist) are not an
//! error for a dev build: the build prints a `cargo:warning` and embeds an empty list with
//! `APPCONTROL_BUILT = false`; at run time the App Control layer then reports
//! `appcontrol_not_built` and deploys nothing. Binaries that exist but do not match their
//! source (stale, hand-rebuilt, wrong id) always fail the build. A release build
//! (`PROFILE=release`) or `RULEBOX_REQUIRE_APPCONTROL=1` makes missing binaries an error too.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

/// The XML sources, by file name without `.xml`, in the order they are embedded.
const POLICIES: [&str; 2] = ["recommended-blocks", "allowlist"];
const VARIANTS: [&str; 2] = ["audit", "enforce"];

/// Why the policies could not be embedded.
enum Problem {
    /// The binaries (or their manifest) are not there: tolerated in a dev build.
    Missing(String),
    /// Something is there but wrong (stale, mismatching, unreadable): always fatal.
    Bad(String),
}

fn fail(message: &str) -> ! {
    // A panic message is how a build script fails; keep it one readable block.
    panic!("\n\nApp Control policies: {message}\nRun `pwsh scripts/appcontrol-build.ps1` from the repository root first (it only writes target\\appcontrol\\).\n");
}

fn bad(message: &str) -> Problem {
    Problem::Bad(message.to_string())
}

/// True when missing binaries must stop the build.
fn strict() -> bool {
    std::env::var("RULEBOX_REQUIRE_APPCONTROL").is_ok_and(|value| value == "1")
        || std::env::var("PROFILE").is_ok_and(|profile| profile == "release")
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().fold(String::with_capacity(bytes.len() * 2), |mut out, b| {
        let _ = write!(out, "{b:02x}");
        out
    })
}

/// SHA-256 of the bytes without carriage returns (same rule as the script).
fn normalized_sha256(bytes: &[u8]) -> String {
    let clean: Vec<u8> = bytes.iter().copied().filter(|b| *b != b'\r').collect();
    hex(&Sha256::digest(clean))
}

/// The text between `<tag>` and `</tag>` (first occurrence), trimmed.
fn element<'a>(xml: &'a str, tag: &str) -> Option<&'a str> {
    let open = format!("<{tag}>");
    let start = xml.find(&open)? + open.len();
    let end = xml[start..].find(&format!("</{tag}>"))? + start;
    Some(xml[start..end].trim())
}

/// The generated source for a build with the binaries.
fn embedded_source() -> Result<String, Problem> {
    let manifest_dir = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_else(|| fail("cargo did not set CARGO_MANIFEST_DIR.")));
    let source_dir = manifest_dir.join("policies").join("appcontrol");
    // The workspace `target` folder: two levels above `apps/agent` (one workspace, one target).
    let built_dir = manifest_dir.join("..").join("..").join("target").join("appcontrol");
    let manifest_path = built_dir.join("sources.txt");
    println!("cargo:rerun-if-changed={}", manifest_path.display());

    let manifest = std::fs::read_to_string(&manifest_path)
        .map_err(|_| Problem::Missing(format!("{} does not exist.", manifest_path.display())))?;

    let mut generated = String::from("// @generated by apps/agent/build.rs; do not edit.\n");
    generated.push_str("pub const APPCONTROL_BUILT: bool = true;\n");
    generated.push_str("pub const EMBEDDED: &[EmbeddedPolicy] = &[\n");
    for name in POLICIES {
        let xml_path = source_dir.join(format!("{name}.xml"));
        println!("cargo:rerun-if-changed={}", xml_path.display());
        let bytes = std::fs::read(&xml_path).map_err(|_| bad(&format!("{} is missing.", xml_path.display())))?;
        let text = String::from_utf8_lossy(&bytes).into_owned();
        let id = element(&text, "PolicyID")
            .ok_or_else(|| bad(&format!("{name}.xml has no PolicyID.")))?
            .trim_matches(|c| c == '{' || c == '}')
            .to_ascii_lowercase();
        let version = element(&text, "VersionEx").ok_or_else(|| bad(&format!("{name}.xml has no VersionEx.")))?;

        let wanted = format!("source {name} {}", normalized_sha256(&bytes));
        if !manifest.lines().any(|line| line == wanted) {
            return Err(bad(&format!("{name}.xml changed after the binaries were built (target\\appcontrol\\sources.txt is stale).")));
        }
        for variant in VARIANTS {
            let file = format!("{id}.{variant}.cip");
            let path = built_dir.join(&file);
            println!("cargo:rerun-if-changed={}", path.display());
            let cip = std::fs::read(&path).map_err(|_| Problem::Missing(format!("{} is missing.", path.display())))?;
            if cip.len() < 20 {
                return Err(bad(&format!("{file} is not a policy binary.")));
            }
            // The binary names its own policy id after a 4-byte format version; check it is
            // the id the XML (and the file name) says, so the agent can never deploy one
            // policy under another's name.
            let guid = id.replace('-', "");
            let mut mixed = String::new();
            for (offset, len, reverse) in [(4usize, 4usize, true), (8, 2, true), (10, 2, true), (12, 8, false)] {
                let mut part: Vec<u8> = cip[offset..offset + len].to_vec();
                if reverse {
                    part.reverse();
                }
                mixed.push_str(&hex(&part));
            }
            if mixed != guid {
                return Err(bad(&format!("{file} holds another policy id than its name.")));
            }
            let sha = hex(&Sha256::digest(&cip));
            let wanted = format!("binary {file} {sha}");
            if !manifest.lines().any(|line| line == wanted) {
                return Err(bad(&format!("{file} does not match target\\appcontrol\\sources.txt (rebuilt by hand?).")));
            }
            let path_text = path.canonicalize().map_err(|_| bad(&format!("{} cannot be resolved.", path.display())))?;
            let path_text = path_text.to_string_lossy().trim_start_matches(r"\\?\").to_string();
            let _ = writeln!(
                generated,
                "    EmbeddedPolicy {{ name: {name:?}, id: {id:?}, version: {version:?}, variant: Variant::{}, sha256: {sha:?}, bytes: include_bytes!({path_text:?}) }},",
                if variant == "audit" { "Audit" } else { "Enforce" },
            );
        }
    }
    generated.push_str("];\n");
    Ok(generated)
}

/// The generated source for a build without the binaries: nothing embedded, a marker the
/// App Control layer checks before it deploys anything.
fn not_built_source() -> String {
    String::from(
        "// @generated by apps/agent/build.rs; do not edit.\n\
         pub const APPCONTROL_BUILT: bool = false;\n\
         pub const EMBEDDED: &[EmbeddedPolicy] = &[];\n",
    )
}

fn embed_app_control() {
    println!("cargo:rerun-if-env-changed=RULEBOX_REQUIRE_APPCONTROL");
    let generated = match embedded_source() {
        Ok(source) => source,
        Err(Problem::Bad(message)) => fail(&message),
        Err(Problem::Missing(message)) if strict() => fail(&message),
        Err(Problem::Missing(message)) => {
            println!(
                "cargo:warning=App Control policies not embedded ({message}) The agent will report appcontrol_not_built and deploy no App Control policy. Run `pwsh scripts/appcontrol-build.ps1` (needs Windows Pro with ConfigCI) before a release build."
            );
            not_built_source()
        }
    };
    let out = PathBuf::from(std::env::var_os("OUT_DIR").unwrap_or_else(|| fail("cargo did not set OUT_DIR."))).join("appcontrol_embedded.rs");
    write_if_changed(&out, &generated);
}

fn write_if_changed(path: &Path, text: &str) {
    if std::fs::read_to_string(path).is_ok_and(|old| old == text) {
        return;
    }
    if std::fs::write(path, text).is_err() {
        fail("cannot write the generated file.");
    }
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    embed_app_control();
    let windows_msvc = std::env::var("CARGO_CFG_TARGET_OS").is_ok_and(|os| os == "windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").is_ok_and(|env| env == "msvc");
    if !windows_msvc {
        return;
    }
    // Rust always links the release (non-debug) CRT, also in debug builds.
    println!("cargo:rustc-link-arg-bins=/NODEFAULTLIB:vcruntime.lib");
    println!("cargo:rustc-link-arg-bins=/NODEFAULTLIB:vcruntimed.lib");
    println!("cargo:rustc-link-arg-bins=libvcruntime.lib");
}
