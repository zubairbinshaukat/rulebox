/**
 * Every user-visible sentence of the dashboard. Functions for interpolation;
 * counts go through `Intl.PluralRules` (`plural`) and `formatCount` so
 * "0 devices", "1 device", "500+ devices" all read right.
 *
 * Keep sentences short and plain: the people using this run a shop, not a
 * data centre.
 */
