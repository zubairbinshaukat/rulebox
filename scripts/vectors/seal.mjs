#!/usr/bin/env node
// Sealed-box test vectors `rulebox.seal/1` (plan Phase 5 Step 1, Section 4.18).
//
//   node scripts/vectors/seal.mjs           write crates/rulebox-policy/tests/vectors/seal.json
//   node scripts/vectors/seal.mjs --check   exit 1 when the committed file differs
//
// Uses @noble/curves (X25519), @noble/hashes (HKDF-SHA256) and @noble/ciphers
// (XChaCha20-Poly1305): an implementation independent of the Rust crates
// (x25519-dalek, hkdf, chacha20poly1305) that opens the boxes in
// crates/rulebox-policy/src/seal.rs. Every secret and nonce below is derived from a
// fixed label, so a second run writes the same bytes. These are TEST keys: they
// protect nothing and are never used anywhere else.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { x25519 } from "@noble/curves/ed25519.js";
import { xchacha20poly1305 } from "@noble/ciphers/chacha.js";
import { hkdf } from "@noble/hashes/hkdf.js";
import { sha256 } from "@noble/hashes/sha2.js";
import { bytesToHex, concatBytes, utf8ToBytes } from "@noble/hashes/utils.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outPath = join(root, "crates", "rulebox-policy", "tests", "vectors", "seal.json");

const b64 = (bytes) => Buffer.from(bytes).toString("base64");
const fromLabel = (label) => sha256(utf8ToBytes(`rulebox.seal/1 test vector: ${label}`));
const keyIdOf = (publicKey) => bytesToHex(sha256(publicKey).slice(0, 8));

const deviceSecret = fromLabel("device secret");
const devicePublic = x25519.getPublicKey(deviceSecret);
const otherSecret = fromLabel("another device secret");
const otherPublic = x25519.getPublicKey(otherSecret);

function seal({ plaintext, toPublic, ephemeralLabel, nonceLabel, orgId, deviceId, profileId }) {
  const ephemeralSecret = fromLabel(ephemeralLabel);
  const epk = x25519.getPublicKey(ephemeralSecret);
  const nonce = fromLabel(nonceLabel).slice(0, 24);
  const shared = x25519.getSharedSecret(ephemeralSecret, toPublic);
  const info = utf8ToBytes(`rulebox.seal/1|${orgId}|${deviceId}|wifi|${profileId}`);
  const key = hkdf(sha256, shared, concatBytes(epk, toPublic), info, 32);
  const ct = xchacha20poly1305(key, nonce).encrypt(utf8ToBytes(plaintext));
  return {
    ephemeralSecret: b64(ephemeralSecret),
    nonceBytes: b64(nonce),
    box: { v: 1, keyId: keyIdOf(toPublic), epk: b64(epk), nonce: b64(nonce), ct: b64(ct) },
  };
}

const base = { orgId: "org_test_vector_1", deviceId: "dev_test_vector_1", profileId: "wifi_test_vector_1" };

const cases = [
  ["ascii", "correct horse battery staple", base],
  ["max-length", "p".repeat(63), { ...base, profileId: "wifi_test_vector_2" }],
  ["unicode", "pässwörd ✓ 日本語", { ...base, deviceId: "dev_test_vector_2" }],
].map(([name, plaintext, ids], index) => ({
  name,
  ...ids,
  plaintext,
  ...seal({ plaintext, toPublic: devicePublic, ephemeralLabel: `ephemeral ${name}`, nonceLabel: `nonce ${name}`, ...ids }),
}));

// Boxes the agent must refuse. All are made for `base`, then opened with something else.
const sample = seal({ plaintext: "top secret", toPublic: devicePublic, ephemeralLabel: "ephemeral negative", nonceLabel: "nonce negative", ...base });
const flipped = Buffer.from(sample.box.ct, "base64");
flipped[0] ^= 1;
const negative = [
  { name: "other-device-id", reason: "open", ...base, deviceId: "dev_test_vector_other", box: sample.box },
  { name: "other-org-id", reason: "open", ...base, orgId: "org_test_vector_other", box: sample.box },
  { name: "other-profile-id", reason: "open", ...base, profileId: "wifi_test_vector_other", box: sample.box },
  { name: "tampered-ciphertext", reason: "open", ...base, box: { ...sample.box, ct: b64(flipped) } },
  {
    name: "sealed-for-another-device-key",
    reason: "wrongKey",
    ...base,
    box: seal({ plaintext: "top secret", toPublic: otherPublic, ephemeralLabel: "ephemeral other", nonceLabel: "nonce other", ...base }).box,
  },
  { name: "unsupported-version", reason: "badVersion", ...base, box: { ...sample.box, v: 2 } },
  { name: "short-nonce", reason: "badEncoding", ...base, box: { ...sample.box, nonce: b64(new Uint8Array(23)) } },
];

const out = {
  note: "Generated by scripts/vectors/seal.mjs with @noble/curves, @noble/hashes and @noble/ciphers. Test keys only. Do not edit by hand.",
  format: "rulebox.seal/1",
  deviceSecret: b64(deviceSecret),
  devicePublic: b64(devicePublic),
  keyId: keyIdOf(devicePublic),
  cases,
  negative,
};
const text = `${JSON.stringify(out, null, 2)}\n`;

// Self-check with the same library before anything is written: every case opens.
for (const c of cases) {
  const epk = Buffer.from(c.box.epk, "base64");
  const shared = x25519.getSharedSecret(deviceSecret, epk);
  const info = utf8ToBytes(`rulebox.seal/1|${c.orgId}|${c.deviceId}|wifi|${c.profileId}`);
  const key = hkdf(sha256, shared, concatBytes(epk, devicePublic), info, 32);
  const plain = xchacha20poly1305(key, Buffer.from(c.box.nonce, "base64")).decrypt(Buffer.from(c.box.ct, "base64"));
  if (Buffer.from(plain).toString("utf8") !== c.plaintext) throw new Error(`self-check failed: ${c.name}`);
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outPath, "utf8");
  } catch {
    /* missing */
  }
  if (current.replace(/\r\n/g, "\n") !== text) {
    console.error("seal.json differs; run: node scripts/vectors/seal.mjs");
    process.exit(1);
  }
  console.log("seal.json is up to date");
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, text);
  console.log(`wrote ${outPath}`);
}
