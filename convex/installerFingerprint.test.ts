beforeEach(() => {
  auditPolicy.strict = true;
});
afterEach(() => {
  auditPolicy.strict = false;
  vi.unstubAllGlobals();
});

async function admin(t: T, orgId: Id<"organizations">) {
  const m = await asMember(t, { role: "admin", orgId });
  await giveStepUp(t, m);
  return m;
}
async function setup() {
  const t = await setupAuth();
  const orgId = await makeOrg(t);
  return { t, orgId, a: await admin(t, orgId) };
}
async function refusal(p: Promise<unknown>): Promise<{ code: string; field?: string; detail?: string } | null> {
  try {
    await p;
    return null;
  } catch (e) {
    return (e as { data: { code: string; field?: string; detail?: string } }).data;
  }
}

describe("apps:fingerprintInstaller", () => {
  test("answers the hash, the size and the installer type; stores nothing", async () => {
    const { t, a } = await setup();
    const body = FIXTURES.nsisHigh();
    const host = fileHost({ [URL1]: { body } });
    vi.stubGlobal("fetch", host.fetch);
    const r = await a.as.action(api.apps.fingerprintInstaller, { url: ` ${URL1} ` });
    expect(Object.keys(r).sort()).toEqual(["inspection", "sha256", "sizeBytes"]);
    expect(r).toMatchObject({
      sha256: hexOf(body),
      sizeBytes: body.length,
      inspection: { tech: "nsis", kind: "exe", confidence: "high", silentArgs: ["/S"], successExitCodes: [0], needsAnswerFile: false, perUserLikely: true, fileVersion: "1.2.3.4", productName: "Fixture App" },
    });
    expect(host.calls).toHaveLength(1);
    expect(await t.run((ctx) => ctx.db.query("apps").take(1))).toEqual([]);
    expect(await t.run((ctx) => ctx.db.system.query("_storage").take(1))).toEqual([]);
    // an MSI
    vi.stubGlobal("fetch", fileHost({ [URL1]: { body: FIXTURES.msi() } }).fetch);
    expect(await a.as.action(api.apps.fingerprintInstaller, { url: URL1 })).toMatchObject({ sha256: hexOf(FIXTURES.msi()), inspection: { tech: "msi", kind: "msi", silentArgs: [] } });
  });

  test("refusals name the field and the reason; a bad address is refused before any request or rate-limit charge", async () => {
    const { a } = await setup();
    const host = fileHost({
      [URL1]: { body: FIXTURES.nsisHigh(), declaredLength: 600 * MIB },
      "https://downloads.example.com/page": { body: new TextEncoder().encode("<html></html>") },
      "https://downloads.example.com/to-private": { body: new Uint8Array(0), redirect: "https://10.0.0.1/a.exe" },
    });
    vi.stubGlobal("fetch", host.fetch);
    for (const url of ["http://downloads.example.com/a.exe", "nonsense", ""]) {
      expect(await refusal(a.as.action(api.apps.fingerprintInstaller, { url })), url).toMatchObject({ code: "invalid_argument", field: "url" });
    }
    expect(host.calls).toEqual([]);
    expect(await refusal(a.as.action(api.apps.fingerprintInstaller, { url: URL1 }))).toMatchObject({ code: "invalid_argument", field: "url", detail: "fingerprint_too_large" });
    expect(await refusal(a.as.action(api.apps.fingerprintInstaller, { url: "https://downloads.example.com/page" }))).toMatchObject({ field: "url", detail: "fingerprint_not_installer" });
    expect(await refusal(a.as.action(api.apps.fingerprintInstaller, { url: "https://downloads.example.com/to-private" }))).toMatchObject({ detail: "fingerprint_blocked" });
    expect(await refusal(a.as.action(api.apps.fingerprintInstaller, { url: "https://downloads.example.com/missing" }))).toMatchObject({ detail: "fingerprint_failed" });
    expect(host.calls.map((c) => c.url)).not.toContain("https://10.0.0.1/a.exe");
    // the three bad addresses above cost nothing: of the 10 an hour, 4 were used by the refusals above, so 6 more are left
    vi.stubGlobal("fetch", fileHost({ [URL1]: { body: FIXTURES.msi() } }).fetch);
    for (let i = 0; i < 6; i++) await a.as.action(api.apps.fingerprintInstaller, { url: URL1 });
    await expectCode(a.as.action(api.apps.fingerprintInstaller, { url: URL1 }), "rate_limited");
  });

  test("a viewer cannot use it; 10 an hour per organization, and another organization has its own", async () => {
    const t = await setupAuth();
    const orgA = await makeOrg(t, "A");
    const orgB = await makeOrg(t, "B");
    const viewer = await asMember(t, { role: "viewer", orgId: orgA });
    vi.stubGlobal("fetch", fileHost({ [URL1]: { body: FIXTURES.msi() } }).fetch);
    await expectCode(viewer.as.action(api.apps.fingerprintInstaller, { url: URL1 }), "forbidden");
    const a = await admin(t, orgA);
    for (let i = 0; i < 10; i++) await a.as.action(api.apps.fingerprintInstaller, { url: URL1 });
    await expectCode(a.as.action(api.apps.fingerprintInstaller, { url: URL1 }), "rate_limited");
    const b = await admin(t, orgB);
    expect(await b.as.action(api.apps.fingerprintInstaller, { url: URL1 })).toMatchObject({ inspection: { tech: "msi" } });
  });

  test("MEASURED: one call reads only the authorization (the download and the rate limiter component are outside the probe)", async () => {
    const { a } = await setup();
    vi.stubGlobal("fetch", fileHost({ [URL1]: { body: FIXTURES.msi() } }).fetch);
    const { io } = await probe(() => a.as.action(api.apps.fingerprintInstaller, { url: URL1 }));
    console.log(`IO apps:fingerprintInstaller reads ${io.reads} (${io.readBytes} B) writes ${io.writes} (${io.writeBytes} B) tables ${[...io.tables].join(",")}`);
    // 3 reads (session, member, step-up); the rate-limiter component's one row (read + write) is not seen by the probe. Budget: 6 / 1.
    expect({ reads: io.reads, writes: io.writes }).toEqual({ reads: 3, writes: 0 });
  });
});
