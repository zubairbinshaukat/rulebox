// `apps:fingerprintInstaller` (UI pass add-app D8): the file is streamed once, hashed and detected. Every test stubs `fetch`: no test
// downloads a real file (the biggest body here is a few MiB of generated bytes).

const URL1 = "https://downloads.example.com/setup.exe";
const MIB = 1024 * 1024;
const hexOf = (b: Uint8Array): string => bytesToHex(sha256(b));
const same = (a: Uint8Array | undefined, b: Uint8Array): boolean => a !== undefined && a.length === b.length && a.every((x, i) => x === b[i]);

type Route = { body: Uint8Array; chunk?: number; declaredLength?: number | null; status?: number; redirect?: string; headers?: Record<string, string> };

/** A host that answers a plain GET with the whole file in chunks of `chunk` bytes (a Range header is ignored, as this action sends none). */
function fileHost(routes: Record<string, Route>) {
  const calls: { url: string; headers: Record<string, string> }[] = [];
  let served = 0;
  const f = (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    calls.push({ url, headers: Object.fromEntries(new Headers(init?.headers).entries()) });
    const r = routes[url];
    if (r === undefined) return new Response("nope", { status: 404 });
    if (r.redirect !== undefined) return new Response(null, { status: 302, headers: { location: r.redirect } });
    if (r.status !== undefined) return new Response(null, { status: r.status });
    const body = r.body;
    const chunk = r.chunk ?? 16 * 1024;
    let at = 0;
    // No read-ahead (`highWaterMark: 0`): `served` counts what the reader really asked for.
    const stream = new ReadableStream<Uint8Array>(
      {
        pull(ctl) {
          if (at >= body.length) return ctl.close();
          const next = body.slice(at, at + chunk);
          at += next.length;
          served += next.length;
          ctl.enqueue(next);
        },
      },
      { highWaterMark: 0 },
    );
    const headers: Record<string, string> = { ...r.headers };
    if (r.declaredLength !== null) headers["content-length"] = String(r.declaredLength ?? body.length);
    return new Response(stream, { status: 200, headers });
  }) as typeof fetch;
  return { fetch: f, calls, bytesServed: () => served };
}

/** A signed installer of a few MiB whose last bytes hold a marker only the tail has. */
function bigSignedInno(): { body: Uint8Array; table: Uint8Array } {
  const table = certificateTable("Big Software Co");
  const tailText = new TextEncoder().encode("..Inno Setup Setup Data (6.2)");
  const overlay = new Uint8Array(3 * MIB + 123);
  for (let i = 0; i < overlay.length; i += 997) overlay[i] = i & 0xff; // not all zeros, so a wrong offset changes the hash
  overlay.set(tailText, overlay.length - tailText.length);
  return { body: buildPe({ overlay, certificate: table }), table };
}

describe("FingerprintCapture", () => {
  test("the hash is SHA-256 of every byte, however the file is cut into chunks", async () => {
    for (const body of [FIXTURES.nsisHigh(), FIXTURES.msi(), buildPe({ overlay: new Uint8Array(200_000).fill(7) }), bigSignedInno().body]) {
      const want = hexOf(body);
      for (const size of [1, 7, 4096, 65_537, INSPECT_HEAD_BYTES + 1, body.length]) {
        // one byte at a time over MiBs would be slow; the big file is only cut into larger pieces
        if (size < 4096 && body.length > 100_000) continue;
        const cap = new FingerprintCapture();
        for (let at = 0; at < body.length; at += size) cap.update(body.subarray(at, at + size));
        const done = cap.finish();
        expect(done.sha256, `${body.length} bytes in ${size}`).toBe(want);
        expect(done.sizeBytes).toBe(body.length);
      }
    }
  });

  test("keeps the head, the certificate table beyond it and the last 64 KiB, whatever the chunk size", () => {
    const { body, table } = bigSignedInno();
    for (const size of [4096, 65_536, 1_000_003, body.length]) {
      const cap = new FingerprintCapture();
      for (let at = 0; at < body.length; at += size) cap.update(body.subarray(at, at + size));
      const done = cap.finish();
      // (`toEqual` on a 2 MiB typed array takes half a minute: compare the bytes directly)
      expect(same(done.head, body.subarray(0, INSPECT_HEAD_BYTES)), `head, chunks of ${size}`).toBe(true);
      expect(same(done.tail, body.subarray(body.length - INSPECT_TAIL_BYTES)), `tail, chunks of ${size}`).toBe(true);
      expect(same(done.cert, table), `certificate, chunks of ${size}`).toBe(true);
    }
  });

  test("a small file is only a head: no tail, no separate certificate", () => {
    const body = buildPe({ manifest: "<x/>", certificate: certificateTable("Small Co") });
    const cap = new FingerprintCapture();
    cap.update(body);
    const done = cap.finish();
    expect(done.head).toEqual(body);
    expect(done.tail).toBeUndefined();
    expect(done.cert).toBeUndefined();
    // the detector reads the table from the head
    expect(detectInstaller({ head: done.head })).toMatchObject({ signer: "Small Co" });
  });

  test("a file just over the head has a tail of what the head does not hold; a table that straddles the head's end is kept whole", () => {
    // 2 MiB + 1000 bytes: the tail is the 1000 bytes after the head, not 64 KiB.
    const base = buildPe().length;
    const plain = buildPe({ overlay: new Uint8Array(INSPECT_HEAD_BYTES + 1000 - base).fill(3) });
    expect(plain.length).toBe(INSPECT_HEAD_BYTES + 1000);
    const cap = new FingerprintCapture();
    cap.update(plain);
    const done = cap.finish();
    expect(same(done.tail, plain.subarray(INSPECT_HEAD_BYTES))).toBe(true);
    // a table that starts inside the head and ends after it
    const table = certificateTable("Straddle Co");
    const overlay = new Uint8Array(INSPECT_HEAD_BYTES - base - 50).fill(5);
    const straddle = buildPe({ overlay, certificate: table });
    expect(straddle.length - table.length).toBeLessThan(INSPECT_HEAD_BYTES);
    expect(straddle.length).toBeGreaterThan(INSPECT_HEAD_BYTES);
    const range = certificateRange(straddle.subarray(0, INSPECT_HEAD_BYTES))!;
    expect(range.offset).toBeLessThan(INSPECT_HEAD_BYTES);
    for (const size of [1000, straddle.length]) {
      const c = new FingerprintCapture();
      for (let at = 0; at < straddle.length; at += size) c.update(straddle.subarray(at, at + size));
      expect(c.finish().cert, `chunks of ${size}`).toEqual(table);
    }
  });

  test("a table the file ends before (a lying header) is dropped, not half-filled", () => {
    const table = certificateTable("Cut Co");
    const full = buildPe({ overlay: new Uint8Array(3 * MIB), certificate: table });
    const cap = new FingerprintCapture();
    cap.update(full.subarray(0, full.length - 10)); // the download ended early
    expect(cap.finish().cert).toBeUndefined();
  });
});

describe("fingerprintInstallerUrl", () => {
  test("hash and detection equal what the one-shot calls say about the whole file", async () => {
    for (const [name, body] of Object.entries({ nsis: FIXTURES.nsisHigh(), inno: FIXTURES.innoHigh(), burn: FIXTURES.burnHigh(), isMsi: FIXTURES.installshieldMsi(), plain: FIXTURES.plainExe(), msi: FIXTURES.msi() })) {
      const r = await fingerprintInstallerUrl(URL1, { fetch: fileHost({ [URL1]: { body, chunk: 1000 } }).fetch });
      expect(r, name).toMatchObject({ ok: true, sha256: hexOf(body), sizeBytes: body.length });
      expect(r.ok && r.inspection, name).toEqual(detectInstaller({ head: body }));
    }
  });

  test("a big signed file gives the same inspection as the three Range reads of apps:inspectInstaller (certificate and tail included)", async () => {
    const { body } = bigSignedInno();
    const host = fileHost({ [URL1]: { body, chunk: 64 * 1024 } });
    const r = await fingerprintInstallerUrl(URL1, { fetch: host.fetch });
    const ranged = await inspectInstallerUrl(URL1, { fetch: rangeHost({ [URL1]: { body } }).fetch });
    expect(r).toMatchObject({ ok: true, sha256: hexOf(body), sizeBytes: body.length, inspection: { tech: "inno", confidence: "medium", signer: "Big Software Co" } });
    expect(ranged.ok && r.ok && r.inspection).toEqual(ranged.ok ? ranged.inspection : null);
    // one request, the whole file, and nothing asked in pieces
    expect(host.calls).toHaveLength(1);
    expect(host.calls[0]!.headers["range"]).toBeUndefined();
    expect(host.calls[0]!.headers["accept-encoding"]).toBe("identity");
    expect(host.bytesServed()).toBe(body.length);
  });

  test("the size cap is 512 MiB, and a declared size above it is refused before a byte is read", async () => {
    expect(FEED_INSTALLER_MAX_BYTES).toBe(512 * MIB);
    const host = fileHost({ [URL1]: { body: FIXTURES.nsisHigh(), declaredLength: 513 * MIB } });
    expect(await fingerprintInstallerUrl(URL1, { fetch: host.fetch })).toEqual({ ok: false, reason: "too_large" });
    expect(host.bytesServed()).toBe(0);
    // exactly at the cap is allowed (declared)
    const atCap = fileHost({ [URL1]: { body: FIXTURES.nsisHigh(), declaredLength: 512 * MIB } });
    expect(await fingerprintInstallerUrl(URL1, { fetch: atCap.fetch })).toMatchObject({ ok: true });
  });

  test("a body that outgrows a smaller cap is cut off while it arrives (no Content-Length, or a lying one)", async () => {
    const body = buildPe({ overlay: new Uint8Array(3 * MIB) });
    for (const declaredLength of [null, 1000]) {
      const host = fileHost({ [URL1]: { body, declaredLength, chunk: 100_000 } });
      expect(await fingerprintInstallerUrl(URL1, { fetch: host.fetch, maxBytes: MIB }), String(declaredLength)).toEqual({ ok: false, reason: "too_large" });
      expect(host.bytesServed()).toBeLessThan(MIB + 200_000);
    }
    // exactly the cap passes
    const exact = fileHost({ [URL1]: { body: FIXTURES.msi(), declaredLength: null } });
    expect(await fingerprintInstallerUrl(URL1, { fetch: exact.fetch, maxBytes: FIXTURES.msi().length })).toMatchObject({ ok: true });
    expect(await fingerprintInstallerUrl(URL1, { fetch: exact.fetch, maxBytes: FIXTURES.msi().length - 1 })).toEqual({ ok: false, reason: "too_large" });
  });

  test("something that is not an installer is refused: a web page, a zip, an empty file", async () => {
    for (const body of [new TextEncoder().encode("<html>Sign in</html>"), Uint8Array.from([0x50, 0x4b, 3, 4, 0, 0]), new Uint8Array(0)]) {
      expect(await fingerprintInstallerUrl(URL1, { fetch: fileHost({ [URL1]: { body } }).fetch })).toEqual({ ok: false, reason: "not_installer" });
    }
  });

  test("blocked: an address the server may not fetch is never requested, also after a redirect", async () => {
    const host = fileHost({});
    for (const url of ["http://downloads.example.com/a.exe", "https://192.168.1.4/a.exe", "https://localhost/a.exe", "https://downloads.example.com:8443/a.exe", "nonsense"]) {
      expect(await fingerprintInstallerUrl(url, { fetch: host.fetch }), url).toEqual({ ok: false, reason: "blocked" });
    }
    expect(host.calls).toEqual([]);
    const body = FIXTURES.nsisHigh();
    expect(await fingerprintInstallerUrl(URL1, { fetch: fileHost({ [URL1]: { body, redirect: "https://cdn.example.com/s.exe" }, "https://cdn.example.com/s.exe": { body } }).fetch })).toMatchObject({ ok: true });
    for (const to of ["http://cdn.example.com/s.exe", "https://10.0.0.5/s.exe", "https://169.254.169.254/latest", "https://cdn.example.com:8443/s.exe"]) {
      const h = fileHost({ [URL1]: { body, redirect: to }, [to]: { body } });
      expect(await fingerprintInstallerUrl(URL1, { fetch: h.fetch }), to).toEqual({ ok: false, reason: "blocked" });
      expect(h.calls.map((c) => c.url)).toEqual([URL1]);
    }
    // a runtime that follows a redirect on its own (the answer comes from another address than the one asked)
    const followed = (async () => {
      const res = new Response(FIXTURES.msi() as BodyInit, { status: 200 });
      Object.defineProperty(res, "url", { value: "https://10.0.0.5/a.exe" });
      return res;
    }) as unknown as typeof fetch;
    expect(await fingerprintInstallerUrl(URL1, { fetch: followed })).toEqual({ ok: false, reason: "blocked" });
  });

  test("failed: 404, 500, too many redirects, a network error, a stream that breaks, a timeout", async () => {
    expect(await fingerprintInstallerUrl(URL1, { fetch: fileHost({}).fetch })).toEqual({ ok: false, reason: "failed" });
    expect(await fingerprintInstallerUrl(URL1, { fetch: fileHost({ [URL1]: { body: new Uint8Array(1), status: 500 } }).fetch })).toEqual({ ok: false, reason: "failed" });
    expect(await fingerprintInstallerUrl(URL1, { fetch: fileHost({ [URL1]: { body: new Uint8Array(1), redirect: URL1 } }).fetch })).toEqual({ ok: false, reason: "failed" });
    const throwing = (async () => {
      throw new TypeError("network");
    }) as typeof fetch;
    expect(await fingerprintInstallerUrl(URL1, { fetch: throwing })).toEqual({ ok: false, reason: "failed" });
    const breaking = (async () =>
      new Response(
        new ReadableStream<Uint8Array>({
          pull(ctl) {
            ctl.enqueue(FIXTURES.nsisHigh().subarray(0, 100));
            ctl.error(new Error("reset"));
          },
        }),
        { status: 200 },
      )) as unknown as typeof fetch;
    expect(await fingerprintInstallerUrl(URL1, { fetch: breaking })).toEqual({ ok: false, reason: "failed" });
    const hang = ((_u: unknown, init?: RequestInit) => new Promise((_res, rej) => init?.signal?.addEventListener("abort", () => rej(new Error("aborted"))))) as unknown as typeof fetch;
    expect(await fingerprintInstallerUrl(URL1, { fetch: hang, timeoutMs: 20 })).toEqual({ ok: false, reason: "failed" });
  });

  test("a body that is not a stream (no `body`) is hashed whole", async () => {
    const body = buildOle(4096);
    const plain = (async () => {
      const res = new Response(body as BodyInit, { status: 200 });
      Object.defineProperty(res, "body", { value: null });
      Object.defineProperty(res, "arrayBuffer", { value: async () => body.slice().buffer });
      return res;
    }) as unknown as typeof fetch;
    expect(await fingerprintInstallerUrl(URL1, { fetch: plain })).toMatchObject({ ok: true, sha256: hexOf(body), sizeBytes: 4096, inspection: { tech: "msi" } });
  });
});

